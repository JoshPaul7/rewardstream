// Package event defines the ad-event schema shared by all rewardstream services.
package event

import (
	"errors"
	"fmt"
	"time"
)

// ErrInvalid is wrapped by every validation error, so callers can map it to HTTP 400.
var ErrInvalid = errors.New("invalid event")

// Type is the kind of ad event.
type Type string

const (
	TypeImpression    Type = "impression"
	TypeClick         Type = "click"
	TypeInstall       Type = "install"
	TypeRewardGranted Type = "reward_granted"
)

// MaxClockSkew is how far into the future occurred_at may be (client clocks drift).
const MaxClockSkew = 5 * time.Minute

// Event is one ad event. ID is generated by the CLIENT, so a retried request
// carries the same ID and the processor can deduplicate it. A server-generated
// ID would give each retry a new identity and count it twice.
type Event struct {
	ID           string    `json:"event_id"`
	Type         Type      `json:"type"`
	CampaignID   string    `json:"campaign_id"`
	UserID       string    `json:"user_id"`
	OccurredAt   time.Time `json:"occurred_at"`
	RewardAmount int64     `json:"reward_amount,omitempty"`
}

func (t Type) valid() bool {
	switch t {
	case TypeImpression, TypeClick, TypeInstall, TypeRewardGranted:
		return true
	}
	return false
}

// Validate reports whether e is acceptable at time now. now is a parameter
// (not time.Now()) so tests are deterministic.
func (e Event) Validate(now time.Time) error {
	switch {
	case e.ID == "" || len(e.ID) > 64:
		return fmt.Errorf("%w: event_id must be 1-64 characters", ErrInvalid)
	case !e.Type.valid():
		return fmt.Errorf("%w: unknown type %q", ErrInvalid, e.Type)
	case e.CampaignID == "":
		return fmt.Errorf("%w: campaign_id is required", ErrInvalid)
	case e.UserID == "":
		return fmt.Errorf("%w: user_id is required", ErrInvalid)
	case e.OccurredAt.IsZero():
		return fmt.Errorf("%w: occurred_at is required", ErrInvalid)
	case e.OccurredAt.After(now.Add(MaxClockSkew)):
		return fmt.Errorf("%w: occurred_at is more than %s in the future", ErrInvalid, MaxClockSkew)
	case e.Type == TypeRewardGranted && e.RewardAmount <= 0:
		return fmt.Errorf("%w: reward_granted needs reward_amount > 0", ErrInvalid)
	case e.Type != TypeRewardGranted && e.RewardAmount != 0:
		return fmt.Errorf("%w: reward_amount is only allowed on reward_granted", ErrInvalid)
	}
	return nil
}
